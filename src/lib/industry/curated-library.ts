// ─── Helper: fetch curated URLs for an industry × category ────────────────

export function getCuratedImages(
  industryId: string,
  category: ImageCategory,
  count = 8
): string[] {
  const entry = CURATED_LIBRARY[industryId];
  if (!entry) return [];
  const list = entry[category] || [];
  // If we need more than available, cycle through the list
  if (list.length >= count) return list.slice(0, count);
  const out = [...list];
  let i = 0;
  while (out.length < count && list.length > 0) {
    out.push(list[i % list.length]);
    i++;
  }
  return out;
}

// ─── Helper: get all curated URLs for an industry (all categories) ────────

export function getAllCuratedImages(
  industryId: string,
  perCategory = 4
): Record<ImageCategory, string[]> {
  const cats: ImageCategory[] = ['hero', 'product', 'lifestyle', 'team', 'workspace', 'detail'];
  const out: Partial<Record<ImageCategory, string[]>> = {};
  for (const c of cats) {
    out[c] = getCuratedImages(industryId, c, perCategory);
  }
  return out as Record<ImageCategory, string[]>;
}
